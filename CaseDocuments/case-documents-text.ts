const norwegianLanguageIds = [1044, 2068];

export function caseTextFor(languageId: number): CaseText {
  return norwegianLanguageIds.includes(languageId) ? nb : en;
}

export const CaseTextContext = React.createContext<CaseText>(en);

export function useCaseText(): CaseText {
  return React.useContext(CaseTextContext);
}
